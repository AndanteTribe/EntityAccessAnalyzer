using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

namespace EntityAccessAnalyzer;

/// <summary>
/// Compilation-wide type resolution, generated-tree classification and signature comparisons.
/// </summary>
internal static class CompilationExtensions
{
    /// <summary>
    /// Resolves the allowed collection types.
    /// </summary>
    public static HashSet<INamedTypeSymbol> ResolveAllowedCollections(this Compilation compilation) =>
        compilation.ResolveReferencedTypes(EntityApiTypeNames.AllowedCollections.Span);

    /// <summary>
    /// Resolves recursive types other than the allowed collections.
    /// </summary>
    public static HashSet<INamedTypeSymbol> ResolveAdditionalRecursiveTypes(this Compilation compilation) =>
        compilation.ResolveReferencedTypes(EntityApiTypeNames.RecursiveTypes.Span);

    /// <summary>
    /// Resolves the explicitly prohibited mutable types.
    /// </summary>
    public static HashSet<INamedTypeSymbol> ResolveMutableTypes(this Compilation compilation) =>
        compilation.ResolveReferencedTypes(EntityApiTypeNames.MutableTypes.Span);

    /// <summary>
    /// Resolves the enumeration interfaces.
    /// </summary>
    public static HashSet<INamedTypeSymbol> ResolveEnumerationTypes(this Compilation compilation) =>
        compilation.ResolveReferencedTypes(EntityApiTypeNames.EnumerationTypes.Span);

    /// <summary>
    /// Collects generated syntax trees, prioritizing SyntaxTreeOptionsProvider over the generated_code setting,
    /// then falling back to file names and auto-generated headers. An explicit non-generated setting stops fallback.
    /// </summary>
    public static HashSet<SyntaxTree> GetGeneratedTrees(
        this Compilation compilation,
        AnalyzerConfigOptionsProvider optionsProvider,
        CancellationToken cancellationToken)
    {
        var generatedTrees = new HashSet<SyntaxTree>();
        foreach (var tree in compilation.SyntaxTrees)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var generatedKind = compilation.Options.SyntaxTreeOptionsProvider?.IsGenerated(tree, cancellationToken);
            switch (generatedKind)
            {
                case GeneratedKind.MarkedGenerated:
                    generatedTrees.Add(tree);
                    continue;
                case GeneratedKind.NotGenerated:
                    continue;
            }
            if (optionsProvider.GetOptions(tree).TryGetValue("generated_code", out var configured)
                && bool.TryParse(configured, out var isGenerated))
            {
                if (isGenerated)
                {
                    generatedTrees.Add(tree);
                }
                continue;
            }

            var fileName = Path.GetFileName(tree.FilePath);
            if (fileName.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase)
                || fileName.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
                || fileName.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase)
                || fileName.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
                || fileName.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)
                || tree.GetRoot(cancellationToken).GetLeadingTrivia().Any(
                    static trivia => trivia.ToString().IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
                        || trivia.ToString().IndexOf("<autogenerated", StringComparison.OrdinalIgnoreCase) >= 0))
            {
                generatedTrees.Add(tree);
            }
        }
        return generatedTrees;
    }

    /// <summary>
    /// Compares parameter signatures for C# member hiding. Method type parameters must already be substituted.
    /// </summary>
    public static bool HaveSameParameterSignature(
        this Compilation compilation,
        ImmutableArray<IParameterSymbol> left,
        ImmutableArray<IParameterSymbol> right)
    {
        if (left.Length != right.Length)
        {
            return false;
        }
        for (var i = 0; i < left.Length; i++)
        {
            // ref, out and in have the same signature for hiding; by-value parameters are distinct.
            if ((left[i].RefKind == RefKind.None) != (right[i].RefKind == RefKind.None)
                || !compilation.ClassifyCommonConversion(left[i].Type, right[i].Type).IsIdentity)
            {
                return false;
            }
        }
        return true;
    }

    /// <summary>
    /// Resolves metadata names, excluding missing types and definitions in the current assembly.
    /// </summary>
    private static HashSet<INamedTypeSymbol> ResolveReferencedTypes(this Compilation compilation, ReadOnlySpan<string> metadataNames)
    {
        var types = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var name in metadataNames)
        {
            var type = compilation.GetTypeByMetadataName(name);
            if (type != null && !SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, compilation.Assembly))
            {
                types.Add(type);
            }
        }
        return types;
    }
}
