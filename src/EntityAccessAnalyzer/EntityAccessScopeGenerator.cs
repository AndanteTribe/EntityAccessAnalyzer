using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace EntityAccessAnalyzer;

/// <summary>
/// Generates the assembly-level configuration attribute in the consuming project.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class EntityAccessScopeGenerator : IIncrementalGenerator
{
    internal const string AttributeMetadataName = "EntityAccessAnalyzer.EntityAccessScopeAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static context => context.AddSource(
            "EntityAccessScopeAttribute.g.cs", SourceText.From("""
                // <auto-generated/>
                namespace EntityAccessAnalyzer
                {
                    /// <summary>
                    /// Identifies namespaces whose types are treated as entities.
                    /// </summary>
                    /// <remarks>
                    /// Uses case-sensitive MatchesSimpleExpression wildcards: * and ?. Dots are literal characters.
                    /// A namespace is included when any pattern matches.
                    /// </remarks>
                    [global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = false, Inherited = false)]
                    internal sealed class EntityAccessScopeAttribute : global::System.Attribute
                    {
                        public readonly string[] NamespacePatterns;

                        public EntityAccessScopeAttribute(params string[] namespacePatterns)
                        {
                            NamespacePatterns = namespacePatterns;
                        }
                    }
                }
                """, Encoding.UTF8)));
    }
}
